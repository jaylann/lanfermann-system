import { spring } from "motion";

type SpringTable = Record<string, { visualDuration: number; bounce: number }>;

/**
 * Renders the spring table as CSS: per spring an easing (`linear()` samples of the real spring), a
 * duration, and a `spring-<name>` utility that sets both on a transition. Pure, so the drift test
 * can compare its output with the checked-in file.
 *
 * Under reduced motion every spring collapses to a short ease-out; the components additionally
 * drop scale and travel (see motion.css), so only opacity changes remain.
 */
export function renderMotionCss(springs: SpringTable): string {
  const names = Object.keys(springs);
  const compiled = names.map((name) => {
    const { visualDuration, bounce } = springs[name]!;
    // Motion stringifies a spring as "<duration>ms linear(...)".
    const css = String(spring(visualDuration, bounce));
    const split = css.indexOf(" ");
    return { name, duration: css.slice(0, split), easing: css.slice(split + 1) };
  });

  const theme = compiled
    .map(
      ({ name, duration, easing }) =>
        `  --ease-spring-${name}: ${easing};\n  --transition-duration-spring-${name}: ${duration};`,
    )
    .join("\n");

  const utilities = compiled
    .map(
      ({ name }) => `@utility spring-${name} {
  --tw-ease: var(--ease-spring-${name});
  --tw-duration: var(--transition-duration-spring-${name});
  transition-timing-function: var(--ease-spring-${name});
  transition-duration: var(--transition-duration-spring-${name});
}`,
    )
    .join("\n");

  const reduced = compiled
    .map(
      ({ name }) =>
        `    --ease-spring-${name}: ease-out;\n    --transition-duration-spring-${name}: 100ms;`,
    )
    .join("\n");

  return `/* GENERATED by scripts/generate-motion-css.ts from src/motion/springs.ts. Do not edit:
   change the spring table and run \`bun run gen:motion\`. */

@theme static {
${theme}
}

${utilities}

@media (prefers-reduced-motion: reduce) {
  :root {
${reduced}
  }
}
`;
}
